"""
resonance_attention.py — SUBLEQ Branch Attention with Resonance-generated projections.

Wires the Resonance ISA oscillator (UMO) into the SUBLEQ attention mechanism:

  Standard SBA:
    W_q, W_k, W_v = nn.Linear (learned)
    scores        = SUBLEQ_compete(Q, K)
    attn          = scores @ V

  Resonance SBA (this module):
    W_q, W_k, W_v = waveform_tensor(umo, shape)  ← oscillator-generated, no random seed
    scores        = SUBLEQ_compete(Q, K)          ← same binary competition
    opcode        = plugboard.route(band)         ← BRANCH taken → Abjad opcode
    attn          = scores @ V

Entropy gate (mirrors sba/kernel.py AGIKernelState invariant):
  UMO.coherent() requires ε < 0.21 and τ > 0.5
  Incoherent field → zero weight projections → SILENCE (no attention output)

The two entropy constants are the same invariant:
  kernel.py    : entropy_budget ≤ 0.20
  umo.coherent : ε < 0.21
  → coherent field is exactly within the kernel's entropy budget.
"""

