def from_drain_invariants(
    inv:       DrainInvariants,
    dim:       int,
    num_heads: int = 8,
) -> ResonanceSUBLEQAttention:
    """Build a ResonanceSUBLEQAttention directly from drain pipeline output."""
    umo = invariants_to_umo(inv)
    return ResonanceSUBLEQAttention(umo=umo, dim=dim, num_heads=num_heads)


def demo_attention(dim: int = 64, num_heads: int = 4) -> ResonanceSUBLEQAttention:
    """Construct a demo instance with synthetic invariants (coherent field)."""
    umo = Umo(trust=0.85, entropy=0.08, resonance=0.72)
    return ResonanceSUBLEQAttention(umo=umo, dim=dim, num_heads=num_heads)
